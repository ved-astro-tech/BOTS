"""Measure each career-option vote on the known-outcome charts and write the track records the bot uses.

    python -m backtest.option_votes cases.yaml [more.yaml ...] [--write]

Prints, per vote: how often it fired and how often the person's sector was one it points to, against the base
rate. Then a leave-one-out check: for each chart, rebuild the records without it and see whether its real sector
is the first option, or among the three offered, compared with offering the three commonest sectors blindly.
--write saves counts only (no names or birth data) to astrobot/knowledge/stats/career_votes.yaml.
"""
from __future__ import annotations

import sys
from collections import Counter
from datetime import datetime, timezone

import yaml

from astrobot.engine import career_options as co
from astrobot.engine.evidence import Engine
from backtest.facts import _birth

NOW = datetime(2026, 10, 22, tzinfo=timezone.utc)


def collect(paths: list[str]) -> list[tuple[str, str, set[str]]]:
    rows = []
    for path in paths:
        for case in yaml.safe_load(open(path, encoding="utf-8"))["cases"]:
            sector = co.sector_of(case.get("facts") or {})
            if case.get("use") is False or not sector or not case.get("date") or not case.get("time"):
                continue
            e = Engine(_birth(case), "career")
            ev = e.build(NOW)
            rows.append((case["name"], sector, {v.id for v in co.fired(e.chart, e.kp, ev)}))
    return rows


def stats(rows) -> dict:
    out = {"charts": len(rows), "sector_counts": dict(Counter(s for _, s, _ in rows)), "votes": {}}
    for v in co.VOTES:
        hits = [s for _, s, ids in rows if v.id in ids]
        out["votes"][v.id] = {"fired": len(hits), "right": sum(s in v.sectors for s in hits),
                              "sectors": sorted(v.sectors), "source": v.source}
    return out


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    rows = collect(args)
    full = stats(rows)
    n = len(rows)
    print(f"{n} charts with a known sector: {full['sector_counts']}\n")
    print("| Vote | Points to | Fired | Right | Precision | Base rate |")
    print("| --- | --- | --- | --- | --- | --- |")
    for v in co.VOTES:
        r = full["votes"][v.id]
        base = sum(full["sector_counts"].get(s, 0) for s in v.sectors) / n
        prec = f'{r["right"] / r["fired"]:.0%}' if r["fired"] else "-"
        print(f'| {v.says} ({v.source}) | {", ".join(sorted(v.sectors))} | {r["fired"]} | {r["right"]} | {prec} | {base:.0%} |')

    top1 = top3 = blind1 = blind3 = 0
    for i, (name, sector, ids) in enumerate(rows):
        rest = stats(rows[:i] + rows[i + 1:])
        ranked = [o["sector"] for o in co.rank(sorted(ids), rest)]
        blind = [s for s, _ in Counter(rest["sector_counts"]).most_common()] + co.SECTORS
        top1 += ranked[0] == sector
        top3 += sector in ranked[:3]
        blind1 += blind[0] == sector
        blind3 += sector in list(dict.fromkeys(blind))[:3]
    print(f"\nLeave-one-out: first option right {top1}/{n}, real sector among 3 options {top3}/{n}")
    print(f"Blind (commonest sectors): first right {blind1}/{n}, among 3 {blind3}/{n}")

    if "--write" in sys.argv:
        co.STATS_PATH.parent.mkdir(parents=True, exist_ok=True)
        header = ("# Generated by backtest/option_votes.py from the known-outcome charts (counts only, no personal data).\n"
                  f"# {n} charts, {NOW.date()}. Re-run after adding charts.\n")
        co.STATS_PATH.write_text(header + yaml.safe_dump(full, sort_keys=False), encoding="utf-8")
        print(f"wrote {co.STATS_PATH}")


if __name__ == "__main__":
    main()
